#!/usr/bin/env bash
# Puts together the folder SiteGround runs: the openGym API, the built app with its exercise
# media, this folder's start.js, and the API's packages already installed (so SiteGround has
# nothing to build). Run from the repository root after `cd frontend && npm run build`.
#   siteground/assemble.sh <output folder>
set -euo pipefail
OUT="${1:?usage: siteground/assemble.sh <output folder>}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"

test -f "$ROOT/frontend/dist/index.html" || { echo "frontend/dist is missing: build the frontend first" >&2; exit 1; }

rm -rf "$OUT"
mkdir -p "$OUT/public" "$OUT/api"

# The built app, and the 180 px exercise media the web image serves at /exercise-media/
cp -R "$ROOT/frontend/dist/." "$OUT/public/"
cp -R "$ROOT/catalogue/media" "$OUT/public/exercise-media"

# The API: every module server.js imports, the same set api/Dockerfile copies (no tests)
( cd "$ROOT/api" && tar --exclude='./node_modules' --exclude='./test' --exclude='*.test.js' -cf - . ) | ( cd "$OUT/api" && tar -xf - )

cp "$ROOT/siteground/start.js" "$OUT/start.js"

# Optional: the name on the home screen icon, in the browser tab and in the install prompt
# (APP_NAME, set in the workflow). Only the <title>, the iOS home screen title and the manifest
# are touched; the inline script in index.html stays byte-for-byte, as its CSP hash requires.
if [ -n "${APP_NAME:-}" ]; then
  node -e '
    const fs = require("fs"), dir = process.argv[1], name = process.argv[2];
    const esc = s => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
    const mf = dir + "/manifest.json";
    const m = JSON.parse(fs.readFileSync(mf, "utf8"));
    m.name = name; m.short_name = name;
    fs.writeFileSync(mf, JSON.stringify(m, null, 2) + "\n");
    const ix = dir + "/index.html";
    let h = fs.readFileSync(ix, "utf8");
    const before = h;
    h = h.replace(/<title>[^<]*<\/title>/, "<title>" + esc(name) + "</title>")
         .replace(/(<meta name="apple-mobile-web-app-title" content=")[^"]*(")/, "$1" + esc(name) + "$2");
    if (h === before) { console.error("APP_NAME: index.html had no title to change"); process.exit(1); }
    fs.writeFileSync(ix, h);
    console.log("app name set to", name);
  ' "$OUT/public" "$APP_NAME"
fi

# One package.json at the top that SiteGround starts with `npm start`. The API's own dependencies,
# installed here so node finds them from api/server.js by walking up.
node -e '
  const fs = require("fs");
  const api = JSON.parse(fs.readFileSync(process.argv[1] + "/api/package.json", "utf8"));
  const pkg = {
    name: "opengym-siteground",
    version: api.version,
    private: true,
    type: "module",
    license: "AGPL-3.0-or-later",
    description: "openGym, packaged to run as a SiteGround Node.js project (see siteground/README.md in the source repository)",
    main: "start.js",
    scripts: { start: "node start.js" },
    engines: { node: ">=22" },
    dependencies: api.dependencies
  };
  fs.writeFileSync(process.argv[2] + "/package.json", JSON.stringify(pkg, null, 2) + "\n");
' "$ROOT" "$OUT"
( cd "$OUT" && npm install --omit=dev --omit=optional --no-audit --no-fund --ignore-scripts )

cat > "$OUT/README.md" <<'EOF'
# openGym, ready to run on SiteGround

This branch is generated by `.github/workflows/siteground.yml` from `main`. Do not edit it by hand:
change `main` (or sync the fork) and the workflow rebuilds it.

SiteGround Node.js project: start command `npm start`, no build command.
Setup and settings: `siteground/README.md` on the `main` branch.
EOF
echo "assembled $(du -sh "$OUT" | cut -f1) in $OUT"
